//===-- SASSInstPrinter.h - Print SASS in sass-dec dialect ------*- C++ -*-===//
//
// Prints MCInsts in the sass-dec assembler dialect, including the guard
// predicate. The scheduling bracket is appended by SASSAsmPrinter.
//
//===----------------------------------------------------------------------===//

#ifndef LLVM_LIB_TARGET_SASS_MCTARGETDESC_SASSINSTPRINTER_H
#define LLVM_LIB_TARGET_SASS_MCTARGETDESC_SASSINSTPRINTER_H

#include "llvm/MC/MCInstPrinter.h"
#include <string>

namespace llvm {

class SASSInstPrinter : public MCInstPrinter {
public:
  SASSInstPrinter(const MCAsmInfo &MAI, const MCInstrInfo &MII,
                  const MCRegisterInfo &MRI)
      : MCInstPrinter(MAI, MII, MRI) {}

  /// Assembler-safe label for an MC symbol name (`.LBB0_3` -> `LBB0_3`).
  static std::string labelName(StringRef SymName);

  // Autogenerated by TableGen.
  std::pair<const char *, uint64_t>
  getMnemonic(const MCInst &MI) const override;
  void printInstruction(const MCInst *MI, uint64_t Address, raw_ostream &O);
  static const char *getRegisterName(MCRegister Reg);

  void printRegName(raw_ostream &OS, MCRegister Reg) override;
  void printInst(const MCInst *MI, uint64_t Address, StringRef Annot,
                 const MCSubtargetInfo &STI, raw_ostream &O) override;

  void printOperand(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printGroup(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printImm(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printF32Imm(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printNegFlag(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printICC(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printFCC(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printBrTarget(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printGlobalAddr(const MCInst *MI, unsigned OpNo, raw_ostream &O);
  void printSharedAddr(const MCInst *MI, unsigned OpNo, raw_ostream &O);

private:
  void printGroupReg(MCRegister Reg, raw_ostream &O);
  void printOffset(int64_t Off, raw_ostream &O);
};

} // namespace llvm

#endif
