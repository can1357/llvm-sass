"""Generate the SASS backend's fixed-latency tables from nvdisasm's sm_120 latency dump.

The dump (`sm120_latencies.txt`) holds the producer x consumer matrices ptxas
schedules with. For every latency mnemonic the backend emits, this writes:

- `SASSLatency.td`: `defvar LAT_<MNEM> = <id>;` used as each instruction's
  `LatMnem` (stored in TSFlags);
- `SASSLatencyTables.inc`: `TrueGPR`, `TruePred`, `TruePredGuard` and
  `TrueUGPR` arrays indexed `[producer][consumer]`, in cycles.

Cells are the maximum over operand roles: a consumer that reads a GPR in any
slot waits the slowest slot's latency. Predicate guards (`Pg`) and predicate
operands are kept apart because they differ by ~8 cycles.

    python tools/gen_latency.py
"""
from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "sass-dec" / "tools"))
from parse_latencies import Latencies  # noqa: E402

MNEMONICS = """IADD IADD3 IMAD LOP3 SHF ISETP SEL VIMNMX MOV FADD FMUL FFMA FSETP FSEL
FMNMX I2FP F2I MUFU LDG STG LD ST LDS STS LDC LDCU S2R S2UR BAR BRA EXIT PLOP3
PRMT POPC FLO SHFL LEA NOP R2UR UIADD3 UMOV""".split()

OUT = ROOT.parent / "llvm" / "lib" / "Target" / "SASS"


def cell(value: str) -> int:
    if value.isdigit():
        return int(value)
    if m := re.fullmatch(r"HARD\((\d+)\)", value):
        return int(m.group(1))
    return 0  # ORDERED_ZERO and friends: no fixed wait


def matrix(lat: Latencies, res: str, roles: set[str] | None, exclude: set[str] = frozenset()) -> list[list[int]]:
    out = []
    for prod in MNEMONICS:
        row = []
        for cons in MNEMONICS:
            best = 0
            for value, _col, col_roles, _row in lat.lookup("TRUE", res, prod, cons, None):
                wanted = set(col_roles) - exclude if roles is None else set(col_roles) & roles
                if wanted:
                    best = max(best, cell(value))
            row.append(best)
        out.append(row)
    return out


def emit_array(name: str, m: list[list[int]]) -> str:
    rows = ",\n".join("  {" + ", ".join(f"{v:2}" for v in row) + "}" for row in m)
    return f"static const uint8_t {name}[NumLatMnem][NumLatMnem] = {{\n{rows}\n}};\n"


def main() -> None:
    lat = Latencies(str(ROOT / "sass-dec" / "sm120_latencies.txt"))
    tables = {
        "TrueGPR": matrix(lat, "GPR", None),
        "TruePred": matrix(lat, "PRED", None, exclude={"Pg"}),
        "TruePredGuard": matrix(lat, "PRED", {"Pg"}),
        "TrueUGPR": matrix(lat, "UGPR", None),
    }
    header = "// Generated by tools/gen_latency.py from sm120_latencies.txt; do not edit.\n"
    td = header + "".join(f"defvar LAT_{m} = {i};\n" for i, m in enumerate(MNEMONICS))
    (OUT / "SASSLatency.td").write_text(td)
    enum = ",\n".join(f"  LAT_{m} = {i}" for i, m in enumerate(MNEMONICS))
    inc = [header, f"enum LatMnemonic : unsigned {{\n{enum},\n  NumLatMnem = {len(MNEMONICS)}\n}};\n"]
    inc.append("static const char *const LatMnemName[NumLatMnem] = {" + ", ".join(f'"{m}"' for m in MNEMONICS) + "};\n")
    inc += [emit_array(name, m) for name, m in tables.items()]
    (OUT / "SASSLatencyTables.inc").write_text("\n".join(inc))
    for name, m in tables.items():
        nz = sum(v > 0 for row in m for v in row)
        print(f"{name}: {nz} nonzero cells")


if __name__ == "__main__":
    main()
